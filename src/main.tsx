import {createRoot} from 'react-dom/client';
import {Suspense} from 'react';
import App from './App';
import {loadConfig} from '@/lib/config';
import {initializeAuth} from '@/lib/auth';
import PageLoading from './PageLoading';
import './styles.css';
const root=createRoot(document.getElementById('root')!);
root.render(<PageLoading/>);
loadConfig().then(()=>initializeAuth()).then(()=>root.render(<Suspense fallback={<PageLoading/>}><App/></Suspense>)).catch(()=>root.render(<main className="entry"><h1>The portal could not connect.</h1><p>Please check your connection and try again. Your saved review stays on this device.</p><button className="secondary" onClick={()=>location.reload()}>Try again</button></main>));
